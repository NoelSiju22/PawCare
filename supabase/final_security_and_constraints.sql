-- This helper intentionally reads the admin table as the function owner so
-- RLS checks do not recursively call themselves.
CREATE OR REPLACE FUNCTION public.is_admin()
RETURNS boolean
LANGUAGE sql
SECURITY DEFINER
SET search_path = public
STABLE
AS $$
  SELECT EXISTS (
    SELECT 1 FROM public.admin WHERE profile_id = auth.uid()
  );
$$;

