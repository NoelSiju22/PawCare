-- Change a user's application role atomically. The admin table and the
-- veterinarian listing are kept synchronized with profiles.role.
CREATE OR REPLACE FUNCTION public.admin_change_user_role(
  target_user_id uuid,
  new_role text
)
RETURNS public.profiles
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  caller_id uuid := auth.uid();
  target_profile public.profiles;
BEGIN
  IF caller_id IS NULL OR NOT public.is_admin() THEN
    RAISE EXCEPTION 'Only administrators can change roles';
  END IF;

  IF target_user_id = caller_id THEN
    RAISE EXCEPTION 'You cannot change your own administrator role from this screen';
  END IF;

  IF new_role NOT IN ('owner', 'vet', 'admin') THEN
    RAISE EXCEPTION 'Invalid role: %', new_role;
  END IF;

  SELECT * INTO target_profile
  FROM public.profiles
  WHERE id = target_user_id
  FOR UPDATE;

  IF target_profile.id IS NULL THEN
    RAISE EXCEPTION 'Profile not found';
  END IF;

  IF new_role = 'admin' THEN
    DELETE FROM public.vet_availability
    WHERE vet_id IN (SELECT id FROM public.veterinarians WHERE profile_id = target_user_id);
    DELETE FROM public.veterinarians WHERE profile_id = target_user_id;

    INSERT INTO public.admin (profile_id)
    VALUES (target_user_id)
    ON CONFLICT (profile_id) DO NOTHING;
  ELSE
    DELETE FROM public.admin WHERE profile_id = target_user_id;

    IF new_role = 'vet' THEN
      IF NOT EXISTS (
        SELECT 1 FROM public.veterinarians WHERE profile_id = target_user_id
      ) THEN
        INSERT INTO public.veterinarians (
          profile_id, name, specialty, location, fee, experience,
          online, in_person, rating
        )
        VALUES (
          target_user_id,
          COALESCE(target_profile.name, target_profile.email, 'Veterinarian'),
          'General Practice',
          'Not specified',
          0,
          'New on Pawcare',
          true,
          true,
          0
        );
      END IF;
    ELSE
      DELETE FROM public.vet_availability
      WHERE vet_id IN (SELECT id FROM public.veterinarians WHERE profile_id = target_user_id);
      DELETE FROM public.veterinarians WHERE profile_id = target_user_id;
    END IF;
  END IF;

  UPDATE public.profiles
  SET role = new_role
  WHERE id = target_user_id
  RETURNING * INTO target_profile;

  RETURN target_profile;
END;
$$;

REVOKE ALL ON FUNCTION public.admin_change_user_role(uuid, text) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.admin_change_user_role(uuid, text) TO authenticated;

-- Remove a profile and its role-specific records. Existing pet/order/appointment
-- history is intentionally preserved unless the database's own foreign-key
-- rules require otherwise.
CREATE OR REPLACE FUNCTION public.admin_delete_user(target_user_id uuid)
RETURNS boolean
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  IF auth.uid() IS NULL OR NOT public.is_admin() THEN
    RAISE EXCEPTION 'Only administrators can delete users';
  END IF;

  IF target_user_id = auth.uid() THEN
    RAISE EXCEPTION 'You cannot delete your own administrator account';
  END IF;

  DELETE FROM public.vet_availability
  WHERE vet_id IN (SELECT id FROM public.veterinarians WHERE profile_id = target_user_id);
  DELETE FROM public.veterinarians WHERE profile_id = target_user_id;
  DELETE FROM public.admin WHERE profile_id = target_user_id;
  DELETE FROM public.profiles WHERE id = target_user_id;

  RETURN true;
END;
$$;

REVOKE ALL ON FUNCTION public.admin_delete_user(uuid) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.admin_delete_user(uuid) TO authenticated;


-- ----------------------------------------------------------------
-- Role-table synchronization safety net
-- ----------------------------------------------------------------
-- Keep role-specific tables consistent even if profiles.role is changed
-- outside the admin RPC. Admins must never remain in veterinarians.
CREATE OR REPLACE FUNCTION public.sync_role_specific_tables()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  IF NEW.role = 'admin' OR NEW.role = 'owner' THEN
    DELETE FROM public.vet_availability
    WHERE vet_id IN (
      SELECT id FROM public.veterinarians WHERE profile_id = NEW.id
    );

    DELETE FROM public.veterinarians
    WHERE profile_id = NEW.id;

    IF NEW.role = 'admin' THEN
      INSERT INTO public.admin (profile_id)
      VALUES (NEW.id)
      ON CONFLICT (profile_id) DO NOTHING;
    ELSE
      DELETE FROM public.admin WHERE profile_id = NEW.id;
    END IF;
  ELSIF NEW.role = 'vet' THEN
    DELETE FROM public.admin WHERE profile_id = NEW.id;
  END IF;

  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS sync_role_specific_tables_trigger
ON public.profiles;

CREATE TRIGGER sync_role_specific_tables_trigger
AFTER INSERT OR UPDATE OF role
ON public.profiles
FOR EACH ROW
EXECUTE FUNCTION public.sync_role_specific_tables();

REVOKE ALL ON FUNCTION public.sync_role_specific_tables() FROM PUBLIC;

-- Repair any existing inconsistent data: an admin must not also have a
-- veterinarian listing or veterinarian availability.
DELETE FROM public.vet_availability
WHERE vet_id IN (
  SELECT v.id
  FROM public.veterinarians v
  JOIN public.admin a ON a.profile_id = v.profile_id
);

DELETE FROM public.veterinarians
WHERE profile_id IN (
  SELECT profile_id FROM public.admin
);

