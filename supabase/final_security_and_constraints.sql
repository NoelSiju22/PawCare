  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  vet_id bigint NOT NULL REFERENCES public.veterinarians(id) ON DELETE CASCADE,
  day_of_week integer NOT NULL CHECK (day_of_week BETWEEN 0 AND 6),
